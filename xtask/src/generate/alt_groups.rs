//! `cargo x gen alt-groups`: `xtask/data/Alternate_AnimationGroups.json`
//! -> `fnis_patch_gen/src/patch_gen/alternate/generated_group_table.rs`.
//!
//! ```json
//! { "_mtidle": { "id": 0, "count": 21, "animations": ["male/mt_idle.hkx"] }, ... }
//! ```

use std::{fmt::Write as _, path::Path};

use serde_json::{Map, Value};

use crate::Result;

#[derive(serde::Deserialize)]
struct Group {
    id: usize,
    animations: Vec<String>,
}

pub(crate) fn run(ws: &Path) -> Result {
    let json = std::fs::read_to_string(ws.join("xtask/data/Alternate_AnimationGroups.json"))?;
    // `Map` keeps the json order (`preserve_order`), so the table order is stable.
    let groups: Map<String, Value> = serde_json::from_str(&json)?;

    let mut code = String::from(
        "// Generated by `cargo x gen alt-groups` from xtask/data/Alternate_AnimationGroups.json. Do not edit.
#[derive(Debug)]
pub(crate) struct AltGroup {
    #[allow(unused)]
    pub id: usize,
    pub animations: &'static [&'static str],
}

pub(crate) static ALT_GROUPS: phf::Map<&'static str, AltGroup> = phf::phf_map! {
",
    );
    for (name, group) in groups {
        let Group { id, animations } = serde_json::from_value(group)?;
        writeln!(code, "    \"{name}\" => AltGroup {{\n        id: {id},\n        animations: &[")?;
        for animation in animations {
            writeln!(code, "            \"{animation}\",")?;
        }
        writeln!(code, "        ],\n    }},")?;
    }
    code.push_str("};\n");

    let output =
        ws.join("crates/core/fnis_patch_gen/src/patch_gen/alternate/generated_group_table.rs");
    std::fs::write(&output, code)?;
    println!("generated: {}", output.display());
    Ok(())
}
