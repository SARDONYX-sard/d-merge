//! `cargo x gen class-schema`: serde-hkx's class json files -> `nemesis_xml`'s `class_schema.rs`.
//!
//! One table for the Nemesis patch parser and the Patch Editor: the Havok type of each field
//! (a `u8` enum), its class, enum / flags values, serialize-ignored fields, the class signature
//! and parent.
//!
//! The json files come from the `class_generator` dependency's repository
//! (`class_generator::classes_json_dir`), so no path has to be given.

use std::{fmt::Write as _, path::Path};

use class_generator::{
    ClassMap, classes_json_dir,
    cpp_info::{Class, Enum, Member, TypeKind},
    get_inherited_class, get_inherited_members, load_class_map,
};

const OUTPUT: &str = "crates/core/nemesis_xml/src/patch/class_schema.rs";

pub(crate) fn run(ws: &Path) -> crate::Result {
    let classes = load_class_map(classes_json_dir()).map_err(|e| e.to_string())?;
    let mut names: Vec<&String> = classes.keys().collect();
    names.sort();

    let mut out = String::from(HEADER);
    out.push_str("static CLASSES: phf::Map<&'static str, ClassSchema> = phf::phf_map! {\n");
    out.push_str(VARIANT);
    for name in names {
        class_entry(&mut out, &classes[name], &classes);
    }
    out.push_str("};\n");

    let path = ws.join(OUTPUT);
    std::fs::write(&path, out)?;
    println!("wrote {}", path.display());
    Ok(())
}

const HEADER: &str = r#"//! Havok class schema: field types, enum / flags values, serialize-ignored fields, signatures.
//!
//! Generated by `cargo x gen class-schema` from serde-hkx's class json files. Do not edit.

/// Havok member type (`hkClassMember::Type`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum TypeKind {
    Void,
    Bool,
    Char,
    Int8,
    Uint8,
    Int16,
    Uint16,
    Int32,
    Uint32,
    Int64,
    Uint64,
    Real,
    Vector4,
    Quaternion,
    Matrix3,
    Rotation,
    QsTransform,
    Matrix4,
    Transform,
    Zero,
    Pointer,
    FnPtr,
    Array,
    InplaceArray,
    Enum,
    Struct,
    SimpleArray,
    HomogeneousArray,
    Variant,
    CString,
    Ulong,
    Flags,
    Half,
    StringPtr,
    RelArray,
    Max,
}

/// A Havok class. `fields` are in member order (the root parent's first).
#[derive(Debug)]
pub struct ClassSchema {
    pub name: &'static str,
    /// e.g. `0xa4180ca1`
    pub signature: &'static str,
    pub parent: Option<&'static str>,
    pub fields: &'static [FieldSchema],
    /// Field name -> index into `fields`.
    pub index: phf::Map<&'static str, u8>,
}

impl ClassSchema {
    /// A field by name.
    pub fn field(&self, name: &str) -> Option<&'static FieldSchema> {
        self.index.get(name).and_then(|&i| self.fields.get(usize::from(i)))
    }
}

/// A field of a [`ClassSchema`].
#[derive(Debug)]
pub struct FieldSchema {
    pub name: &'static str,
    pub kind: TypeKind,
    /// Element type of an array, storage type of an enum / flags, else [`TypeKind::Void`].
    pub sub_kind: TypeKind,
    /// Class of a struct / pointer / array of them.
    pub class: Option<&'static str>,
    /// Enum or flags values, e.g. `MODE_SINGLE_PLAY`.
    pub values: &'static [&'static str],
    /// Not written in XML (`SERIALIZE_IGNORED`), e.g. `referenceCount`.
    pub serialize_ignored: bool,
}

/// Finds a class by name.
pub fn find_class_schema(name: &str) -> Option<&'static ClassSchema> {
    CLASSES.get(name)
}

/// Every class name (any order).
pub fn class_schema_names() -> impl Iterator<Item = &'static str> {
    CLASSES.keys().copied()
}

"#;

/// `hkVariant` (`TYPE_VARIANT` fields): not a class json, but an object of two pointers.
const VARIANT: &str = r#"    "Variant" => ClassSchema { name: "Variant", signature: "0x0", parent: None, fields: &[
        FieldSchema { name: "object", kind: TypeKind::Pointer, sub_kind: TypeKind::Void, class: None, values: &[], serialize_ignored: false },
        FieldSchema { name: "class", kind: TypeKind::Pointer, sub_kind: TypeKind::Void, class: None, values: &[], serialize_ignored: false },
    ], index: phf::phf_map! { "object" => 0, "class" => 1 } },
"#;

fn class_entry(out: &mut String, class: &Class<'_>, classes: &ClassMap<'_>) {
    let parent =
        class.parent.as_deref().map_or_else(|| "None".to_string(), |p| format!("Some({p:?})"));
    let _ = writeln!(
        out,
        "    {name:?} => ClassSchema {{ name: {name:?}, signature: \"{signature}\", parent: {parent}, fields: &[",
        name = class.name,
        signature = class.signature,
    );
    let inherited = get_inherited_class(&class.name, classes);
    let members = get_inherited_members(&class.name, classes);
    for member in &members {
        field_entry(out, member, &inherited, classes);
    }
    out.push_str("    ], index: phf::phf_map! {");
    for (i, member) in members.iter().enumerate() {
        let _ = write!(out, " {:?} => {i},", member.name);
    }
    out.push_str(" } },\n");
}

fn field_entry(
    out: &mut String,
    member: &Member<'_>,
    inherited: &[&Class<'_>],
    classes: &ClassMap<'_>,
) {
    let enum_def = member.enum_ref.as_deref().and_then(|name| find_enum(name, inherited, classes));
    let values: Vec<String> = enum_def
        .map(|e| e.enum_item.iter().map(|item| format!("{:?}", item.name)).collect())
        .unwrap_or_default();
    let class =
        member.class_ref.as_deref().map_or_else(|| "None".to_string(), |c| format!("Some({c:?})"));
    let _ = writeln!(
        out,
        "        FieldSchema {{ name: {name:?}, kind: TypeKind::{kind}, sub_kind: TypeKind::{sub}, class: {class}, values: &[{values}], serialize_ignored: {ignored} }},",
        name = member.name,
        kind = variant(&member.vtype),
        sub = variant(&member.vsubtype),
        values = values.join(", "),
        ignored = member.flags.has_skip_serializing(),
    );
}

/// `TYPE_QSTRANSFORM` -> `QsTransform` (the generated enum's variant).
fn variant(kind: &TypeKind) -> &'static str {
    match kind.to_string().trim_start_matches("TYPE_") {
        "VOID" => "Void",
        "BOOL" => "Bool",
        "CHAR" => "Char",
        "INT8" => "Int8",
        "UINT8" => "Uint8",
        "INT16" => "Int16",
        "UINT16" => "Uint16",
        "INT32" => "Int32",
        "UINT32" => "Uint32",
        "INT64" => "Int64",
        "UINT64" => "Uint64",
        "REAL" => "Real",
        "VECTOR4" => "Vector4",
        "QUATERNION" => "Quaternion",
        "MATRIX3" => "Matrix3",
        "ROTATION" => "Rotation",
        "QSTRANSFORM" => "QsTransform",
        "MATRIX4" => "Matrix4",
        "TRANSFORM" => "Transform",
        "ZERO" => "Zero",
        "POINTER" => "Pointer",
        "FUNCTIONPOINTER" | "FNPTR" => "FnPtr",
        "ARRAY" => "Array",
        "INPLACEARRAY" => "InplaceArray",
        "ENUM" => "Enum",
        "STRUCT" => "Struct",
        "SIMPLEARRAY" => "SimpleArray",
        "HOMOGENEOUSARRAY" => "HomogeneousArray",
        "VARIANT" => "Variant",
        "CSTRING" => "CString",
        "ULONG" => "Ulong",
        "FLAGS" => "Flags",
        "HALF" => "Half",
        "STRINGPTR" => "StringPtr",
        "RELARRAY" => "RelArray",
        _ => "Max",
    }
}

/// An enum by name: in the class or its parents, else `Class::Enum` / any class (shared enums).
fn find_enum<'a>(
    name: &str,
    inherited: &[&'a Class<'a>],
    classes: &'a ClassMap<'a>,
) -> Option<&'a Enum<'a>> {
    let (owner, enum_name) = name.rsplit_once("::").map_or((None, name), |(o, e)| (Some(o), e));
    if let Some(owner) = owner.and_then(|o| classes.get(o)) {
        return owner.enums.iter().find(|e| e.name == enum_name);
    }
    inherited
        .iter()
        .rev()
        .find_map(|class| class.enums.iter().find(|e| e.name == enum_name))
        .or_else(|| {
            classes.values().find_map(|class| class.enums.iter().find(|e| e.name == enum_name))
        })
}
